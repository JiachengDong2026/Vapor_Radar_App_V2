"""Generate the supported Butterworth profiles (SciPy is a generation dependency)."""
from pathlib import Path
from scipy.signal import butter

CUTOFFS = (100, 250, 500, 1000, 2000, 5000, 10000)
# Preserve the validated default bit for bit, including its rounding convention.
LEGACY = {
    (1000000, 0): (690501114, 1381002230, -139922478782895, 69556496609689),
    (1000000, 1): (692843472, 1385686942, -140397131718583, 70031158914805),
    (12500000, 0): (4442812, 8885622, -140672143489574, 70303417083156),
    (12500000, 1): (4444020, 8888039, -140710403851039, 70341677449454),
}


def coefficients(rate, cutoff, section):
    if cutoff == 1000:
        return LEGACY[rate, section]
    row = butter(4, cutoff, fs=rate, output='sos')[section]
    a1, a2 = round(row[4]*2**46), round(row[5]*2**46)
    b0 = round((1+row[4]+row[5])*2**44)
    return b0, 2**46+a1+a2-2*b0, a1, a2


def generate():
    lines = ['// Generated by fpga/scripts/generate_lpf_coefficients.py.',
             'module dila_lpf_coefficients #(parameter integer INPUT_RATE_HZ=1000000,SECTION=0)(',
             '    input wire [31:0] cutoff_hz,',
             '    output reg signed [47:0] b0,b1,a1,a2',
             ');', '    always @* begin', '        b0=0;b1=0;a1=0;a2=0;', '        case(cutoff_hz)']
    def constant(value):
        return ("-48'sd" if value < 0 else "48'sd") + str(abs(value))
    for cutoff in CUTOFFS:
        lines.append(f'            {cutoff}:begin')
        for name, index in zip(('b0', 'b1', 'a1', 'a2'), range(4)):
            values = [constant(coefficients(rate, cutoff, section)[index])
                      for rate, section in ((12500000, 1), (12500000, 0), (1000000, 1), (1000000, 0))]
            lines.append(f'                {name}=INPUT_RATE_HZ==12500000 ? (SECTION==1 ? {values[0]} : {values[1]}) : (SECTION==1 ? {values[2]} : {values[3]});')
        lines.append('            end')
    lines += ['            default:begin end', '        endcase', '    end', 'endmodule', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    Path(__file__).resolve().parents[1].joinpath('rtl/dila/dila_lpf_coefficients.v').write_text(generate(), encoding='utf-8')
